/**
  ******************************************************************************
  * @file    drv_iwdg.h
  * @brief   独立看门狗(IWDG)驱动头文件 - STM32F103C8T6
  *
  * 功能概述:
  *   - 基于内部LSI（约40kHz）的独立看门狗
  *   - 超时时间配置（毫秒）
  *   - 喂狗（重装载计数器）
  *   - 使能后无法软件关闭，复位只能通过硬件
  *
  * 超时时间计算公式:
  *   Timeout(ms) = (4 * 2^prescaler * reload) / 40000 * 1000
  *   本驱动从目标超时ms自动计算分频和重装值
  *
  * 使用示例:
  *   DRV_IWDG_Init(1000);   // 1000ms超时
  *   // 在主循环中定期调用:
  *   DRV_IWDG_Feed();
  ******************************************************************************
  */

#ifndef __DRV_IWDG_H
#define __DRV_IWDG_H

#include "stm32f10x.h"
#include "stm32f10x_iwdg.h"

/*===========================================================================
 * API 函数声明
 *===========================================================================*/

/**
 * @brief  初始化并启动IWDG
 *         自动根据目标超时时间计算最优分频和重装值
 * @param  timeoutMs  超时时间（毫秒），范围约 1~26000ms（LSI=40kHz时）
 *                    建议 100~5000ms
 */
void DRV_IWDG_Init(uint32_t timeoutMs);

/**
 * @brief  喂狗（重装计数器）
 *         必须在超时时间内定期调用，否则系统复位
 */
void DRV_IWDG_Feed(void);

#endif /* __DRV_IWDG_H */
